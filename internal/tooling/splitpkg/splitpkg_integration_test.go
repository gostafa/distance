func putSources(t *testing.T, dir string, sources map[string]string) {
	t.Helper()
	for name, source := range sources {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func TestSplitPreservesCompilableDeclarationsAndTests(t *testing.T) {
	dir := t.TempDir()
	putSources(t, dir, map[string]string{
		"go.mod":            "module example.com/splitfixture\n\ngo 1.27.2\n",
		"main.go":           "// Package fixture exercises splitting.\npackage fixture\ntype Value struct{Count int}\nconst first=1\nvar current=first\nfunc Read()int{return current}\n",
		"first_test.go":     "package fixture\nimport(\"fmt\";\"testing\")\nfunc TestOne(t *testing.T){if fmt.Sprint(Read())!=\"1\"{t.Fatal(\"wrong value\")}}\n",
		"second_test.go":    "package fixture\nimport(other \"fmt\";\"testing\")\nfunc TestTwo(t *testing.T){if other.Sprint(Read())!=\"1\"{t.Fatal(\"other.Sprint stays literal\")}}\n",
		"outside_test.go":   "package fixture_test\nimport(\"testing\";fixture \"example.com/splitfixture\")\nfunc TestPublic(t *testing.T){if fixture.Read()!=1{t.Fatal(\"wrong public value\")}}\n",
		"old_bench_test.go": "package fixture\nimport \"testing\"\nfunc BenchmarkRead(b *testing.B){for b.Loop(){_ = Read()}}\n",
	})
	if err := splitpkg.SplitPackage(dir); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	got := []string{}
	for _, entry := range entries {
		got = append(got, entry.Name())
	}
	want := []string{
		"consts.go",
		"doc.go",
		"fixture_bench_test.go",
		"fixture_integration_test.go",
		"fixture_test.go",
		"funcs.go",
		"go.mod",
		"types.go",
		"vars.go",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("files: %v want %v", got, want)
	}
	data, err := os.ReadFile(filepath.Join(dir, "fixture_test.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "other.Sprint stays literal") {
		t.Fatal("test fixture literal changed during alias rewriting")
	}
	for _, name := range []string{"doc.go", "funcs.go", "types.go", "consts.go", "vars.go", "fixture_test.go", "fixture_integration_test.go", "fixture_bench_test.go"} {
		if _, err := parser.ParseFile(
			token.NewFileSet(),
			filepath.Join(dir, name),
			nil,
			parser.ParseComments,
		); err != nil {
			t.Fatal(err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = dir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("split package no longer builds: %v\n%s", err, output)
	}
	before, err := os.ReadFile(filepath.Join(dir, "fixture_test.go"))
	if err != nil {
		t.Fatal(err)
	}
	if err := splitpkg.SplitPackage(dir); err != nil {
		t.Fatal(err)
	}
	after, err := os.ReadFile(filepath.Join(dir, "fixture_test.go"))
	if err != nil {
		t.Fatal(err)
	}
	if string(before) != string(after) {
		t.Fatal("test consolidation is not idempotent")
	}
}

func TestSplitDocumentsTestOnlyPackages(t *testing.T) {
	dir := t.TempDir()
	putSources(
		t,
		dir,
		map[string]string{
			"anything_test.go": "package only\nimport \"testing\"\nfunc TestOnly(t *testing.T){}\n",
		},
	)
	if err := splitpkg.SplitPackage(dir); err != nil {
		t.Fatal(err)
	}
	file, err := parser.ParseFile(
		token.NewFileSet(),
		filepath.Join(dir, "doc.go"),
		nil,
		parser.ParseComments,
	)
	if err != nil || file.Doc == nil || file.Name.Name != "only" {
		t.Fatalf("test-only documentation: %v %v", file, err)
	}
}

func TestSplitRejectsUnrepresentableBuildConstraints(t *testing.T) {
	for _, sources := range []map[string]string{
		{"main.go": "//go:build linux\n\npackage constrained\nfunc Work(){}\n"},
		{"main.go": "package mixed\ntype Ordinary struct{}\n", "gen.go": "// Code generated by test. DO NOT EDIT.\npackage mixed\ntype Generated struct{}\n"},
	} {
		dir := t.TempDir()
		putSources(t, dir, sources)
		if err := splitpkg.SplitPackage(dir); err == nil {
			t.Fatal("unrepresentable source constraints silently dropped")
		}
		for name, expected := range sources {
			got, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil || string(got) != expected {
				t.Fatalf("source changed before rejection: %s %v", name, err)
			}
		}
	}
}

func TestSplitPreservesEmbeddedGeneratedDeclarations(t *testing.T) {
	directory := t.TempDir()
	marker := "// Code generated by test. DO NOT EDIT."
	putSources(t, directory, map[string]string{
		"go.mod":       "module example.com/embedfixture\n\ngo 1.27.2\n",
		"payload.txt":  "embedded contents",
		"generated.go": marker + "\npackage fixture\nimport _ \"embed\"\n//go:embed payload.txt\nvar Payload string\n",
	})
	for range 2 {
		if err := splitpkg.SplitPackage(directory); err != nil {
			t.Fatal(err)
		}
		source, err := os.ReadFile(filepath.Join(directory, "vars.go"))
		if err != nil || !strings.Contains(string(source), "var Payload string") ||
			!strings.Contains(string(source), marker) {
			t.Fatalf("embedded/generated declarations lost: %s err=%v", source, err)
		}
	}
	command := exec.CommandContext(t.Context(), "go", "test", "./...")
	command.Dir = directory
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("embedded output failed to build: %v\n%s", err, output)
	}
}
